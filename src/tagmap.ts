/** タグの集合に入っているか */
export const isTag = (s: string): s is Tag => (TAGS as readonly string[]).includes(s);

/**
 * 元データのジャンル語の一覧から、対応表に当たる語のタグを集める。
 * 当たる語がなければ空(= 未整備)。順番は対応表の順で、重複は除く。
 */
export function tagsForGenres(genres: readonly string[]): Tag[] {
  const out: Tag[] = [];
  for (const g of genres) {
    const tags = GENRE_TAGS[g.trim()];
    if (!tags) continue;
    for (const t of tags) if (!out.includes(t)) out.push(t);
  }
  return out;
}
